/**
 * Telemetry page.
 * POLAR TWIN — all data handled here is SYNTHETIC (not NCPOR telemetry).
 */
import { activeStations, sourceBadge, timeAgo } from '../ui/shell.js';
import { fmt1, now, rand } from '../utils/helpers.js';

export function renderTelemetry(){
  const stations = activeStations();
  const rows = [];
  stations.forEach(st=>{
    rows.push({station:st.label, param:'External temperature', val:fmt1(st.env.temp)+'°C', src:'SIMULATED'});
    rows.push({station:st.label, param:'Total power consumption', val:fmt1(st.energy.totalConsumption)+' kW', src:'SIMULATED'});
    rows.push({station:st.label, param:'Fuel inventory', val:fmt1(st.logistics.fuel.qty)+'%', src:'SIMULATED'});
    rows.push({station:st.label, param:'Generator #1 vibration', val:fmt1(st.generators[0].vibration)+' mm/s', src:'SIMULATED'});
    rows.push({station:st.label, param:'Satellite link', val: st.commsOffline?'OFFLINE':'CONNECTED', src: st.commsOffline?'OFFLINE':'LIVE'});
  });
  return `
  <div class="page-head"><div><h1>Data &amp; Telemetry</h1><div class="page-sub">Raw feed inventory and data-source classification</div></div></div>
  <div class="disclaimer-strip">This prototype has no connection to real NCPOR station telemetry, sensors or satellite systems. All values below are generated by the in-browser Antarctic Station Data Simulator. The architecture (MQTT → FastAPI → Digital Twin) is designed so a real feed can be substituted without changing the rest of the system — see ARCHITECTURE.md in the full source package.</div>
  <div class="card">
    <h3>Live Feed Inventory</h3>
    <table><thead><tr><th>Station</th><th>Parameter</th><th>Value</th><th>Source</th><th>Updated</th></tr></thead><tbody>
    ${rows.map(r=>`<tr><td>${r.station}</td><td>${r.param}</td><td><b>${r.val}</b></td><td>${sourceBadge(r.src)}</td><td>${timeAgo(now()-rand(500,3000))}</td></tr>`).join('')}
    </tbody></table>
  </div>
  <div class="card" style="margin-top:16px;">
    <h3>Data Source Legend</h3>
    <div class="metric-row"><span>${sourceBadge('LIVE')}</span><span>Connected feed, updating in real time (simulated satellite/network link).</span></div>
    <div class="metric-row"><span>${sourceBadge('HISTORICAL')}</span><span>Public/historical Antarctic climate reference values.</span></div>
    <div class="metric-row"><span>${sourceBadge('SIMULATED')}</span><span>Generated by the Antarctic Station Data Simulator — no NCPOR sensor behind it.</span></div>
    <div class="metric-row"><span>${sourceBadge('OFFLINE')}</span><span>Link down — values held from local cache, queued for sync.</span></div>
  </div>
  `;
}

